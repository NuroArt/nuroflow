#!/usr/bin/env python3
"""Write .env.prod with fresh, strong secrets. Standard library only.

    python3 deploy/generate-secrets.py --domain flow.example.com > .env.prod

Every secret is URL-safe (it's embedded in database and Redis URLs). Refuses to
overwrite an existing file by design: regenerating NUROFLOW_ENCRYPTION_KEYS would make
every stored connection secret and webhook secret undecryptable.
"""

from __future__ import annotations

import argparse
import base64
import secrets


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--domain", default="localhost")
    args = parser.parse_args()
    fernet = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()
    scheme = "http" if args.domain in ("localhost", "127.0.0.1") else "https"
    print(f"""# Generated by deploy/generate-secrets.py. Keep this file private and backed up.
# Losing NUROFLOW_ENCRYPTION_KEYS means losing every stored credential.

# ---- infrastructure
POSTGRES_PASSWORD={secrets.token_urlsafe(32)}
REDIS_PASSWORD={secrets.token_urlsafe(32)}
GRAFANA_ADMIN_PASSWORD={secrets.token_urlsafe(18)}
DOMAIN={args.domain}
ACME_EMAIL=

# ---- application (NUROFLOW_*; see .env.example for every option)
NUROFLOW_SECRET_KEY={secrets.token_urlsafe(64)}
NUROFLOW_ENCRYPTION_KEYS={fernet}
NUROFLOW_METRICS_TOKEN={secrets.token_urlsafe(32)}
NUROFLOW_PUBLIC_BASE_URL={scheme}://{args.domain}
NUROFLOW_CORS_ORIGINS=
NUROFLOW_DOCS_ENABLED=false
NUROFLOW_REGISTRATION_ENABLED=false
NUROFLOW_LLM_MODE=live
NUROFLOW_TELEGRAM_MODE=live
# Platform-default keys are optional: per-user keys belong in connections (encrypted).
# NUROFLOW_OPENAI_API_KEY=
# NUROFLOW_ANTHROPIC_API_KEY=
# NUROFLOW_TELEGRAM_BOT_TOKEN=
# NUROFLOW_LLM_PRICING={{"gpt-4o-mini": {{"input": 0.15, "output": 0.60}}}}
""", end="")


if __name__ == "__main__":
    main()
